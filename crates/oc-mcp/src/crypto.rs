//! Small crypto helpers for the MCP OAuth flow.
//!
//! The reference (via `@modelcontextprotocol/sdk` and Node's `crypto`) uses
//! SHA-256 + base64url for PKCE (`S256`) code challenges and random bytes for
//! OAuth `state`. Implemented here so the crate needs no Node runtime.
//!
//! TODO(integration): move to oc-util if a general crypto module is needed.

